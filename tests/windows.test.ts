import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { windowRole, visibleSections } from "../src/window-role";
import { EMPTY_DRAFTS, mergeDraftChange } from "../src/state";
test("a draft edit in one window preserves another window's other fields", () => {
  const stored = { ...EMPTY_DRAFTS, outgoing: "Новый ответ", question: "Новый вопрос" };
  const oldWindow = { ...EMPTY_DRAFTS, incoming: "Ahoj" };
  const merged = mergeDraftChange(stored, oldWindow, "incoming");
  assert.equal(merged.incoming, "Ahoj");
  assert.equal(merged.outgoing, "Новый ответ");
  assert.equal(merged.question, "Новый вопрос");
});
test("application, translator and dim layer have distinct routes and independent native properties", () => {
  assert.equal(windowRole(""), "main");
  assert.equal(windowRole("?window=overlay"), "overlay");
  assert.equal(windowRole("?window=unknown"), "main");
  assert.equal(windowRole("", "overlay"), "overlay");
  assert.equal(windowRole("?window=overlay", "main"), "main");
  assert.equal(windowRole("?window=backdrop"), "backdrop");
  assert.equal(windowRole("", "backdrop"), "backdrop");
  assert.deepEqual(visibleSections("main"), ["overlay", "guide"]);
  assert.deepEqual(visibleSections("overlay"), []);
  assert.deepEqual(visibleSections("backdrop"), []);
  const config = JSON.parse(readFileSync(new URL("../src-tauri/tauri.conf.json", import.meta.url), "utf8"));
  assert.equal(config.app.windows.length, 3);
  const main = config.app.windows.find((w: { label: string }) => w.label === "main");
  const overlay = config.app.windows.find((w: { label: string }) => w.label === "overlay");
  assert.equal(main.alwaysOnTop, false);
  assert.equal(main.decorations, true);
  assert.equal(overlay.visible, false);
  assert.equal(overlay.transparent, true);
  assert.equal(overlay.alwaysOnTop, false);
  assert.equal(overlay.width, 360);
  assert.equal(overlay.height, 280);
  assert.equal(overlay.minWidth, 320);
  assert.equal(overlay.minHeight, 240);
  assert.equal(overlay.resizable, true);
  assert.equal(windowRole(new URL(overlay.url, "https://local.test").search), "overlay");
  const backdrop = config.app.windows.find((w: { label: string }) => w.label === "backdrop");
  assert.equal(backdrop.visible, false);
  assert.equal(backdrop.transparent, true);
  assert.equal(backdrop.alwaysOnTop, true);
  assert.equal(backdrop.skipTaskbar, true);
  assert.equal(backdrop.url, "backdrop.html");
  assert.notEqual(backdrop.url, overlay.url);
  const capability = JSON.parse(readFileSync(new URL("../src-tauri/capabilities/main.json", import.meta.url), "utf8"));
  assert.deepEqual(capability.windows.toSorted(), ["backdrop", "main", "overlay"]);
});
